import type { SVGProps } from "react";

/**
 * Brand marks, copied path-for-path from quirq/icons.
 *
 * Only the marks actually rendered are inlined, so the bundle carries those
 * rather than the whole folder, and they are inlined rather than served as
 * files so a mark can take the surrounding text colour: dim in a lattice,
 * ink on hover, no second request.
 *
 * Every mark is flattened to a single colour on the way in. Gradients and
 * their <defs> are dropped, which does three things at once: it keeps the
 * lattice monochrome so one brand's red does not read as a mistake beside
 * eleven greys, it removes the single-letter id collisions that would make one
 * inlined icon steal another's clip path, and it lets hover states work at all.
 * If a full-colour mark is ever wanted, that is a deliberate redesign of the
 * lattice, not a tweak here.
 */

type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & { title?: string };

function Glyph({
  title,
  children,
  viewBox = "0 0 24 24",
  ...props
}: IconProps & { children: React.ReactNode }) {
  // Decorative by default: these sit beside their own text label, so a second
  // announcement is noise. Passing `title` opts back in.
  return (
    <svg
      viewBox={viewBox}
      fill="currentColor"
      fillRule="evenodd"
      width="1em"
      height="1em"
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      {...props}
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

